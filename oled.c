static void OLED_WriteCommand(uint8_t cmd)
{
    uint8_t data[2];
    data[0] = 0x00;   // ????:??
    data[1] = cmd;
    HAL_I2C_Master_Transmit(&hi2c1, OLED_ADDR, data, 2, 100);
}

static void OLED_WriteData(uint8_t *data, uint16_t size)
{
    uint8_t buf[129];
    uint16_t i;

    buf[0] = 0x40;    // ????:??
    for (i = 0; i < size; i++)
    {
        buf[i + 1] = data[i];
    }
    HAL_I2C_Master_Transmit(&hi2c1, OLED_ADDR, buf, size + 1, 100);
}

static void OLED_SetCursor(uint8_t page, uint8_t x)
{
    OLED_WriteCommand(0xB0 + page);
    OLED_WriteCommand(0x10 | ((x & 0xF0) >> 4));
    OLED_WriteCommand(0x00 | (x & 0x0F));
}

void OLED_Clear(void)
{
    uint8_t i, j;
    uint8_t zero[128];

    for (j = 0; j < 128; j++) zero[j] = 0x00;

    for (i = 0; i < 8; i++)
    {
        OLED_SetCursor(i, 0);
        OLED_WriteData(zero, 128);
    }
}

void OLED_Init(void)
{
    HAL_Delay(100);

    OLED_WriteCommand(0xAE); // display off
    OLED_WriteCommand(0x20); // Set Memory Addressing Mode
    OLED_WriteCommand(0x10); // Page addressing mode
    OLED_WriteCommand(0xB0); // Page Start Address
    OLED_WriteCommand(0xC8); // COM Output Scan Direction
    OLED_WriteCommand(0x00); // low column
    OLED_WriteCommand(0x10); // high column
    OLED_WriteCommand(0x40); // start line
    OLED_WriteCommand(0x81); // contrast
    OLED_WriteCommand(0x7F);
    OLED_WriteCommand(0xA1); // segment remap
    OLED_WriteCommand(0xA6); // normal display
    OLED_WriteCommand(0xA8); // multiplex ratio
    OLED_WriteCommand(0x3F);
    OLED_WriteCommand(0xA4); // display follows RAM
    OLED_WriteCommand(0xD3); // display offset
    OLED_WriteCommand(0x00);
    OLED_WriteCommand(0xD5); // osc frequency
    OLED_WriteCommand(0xF0);
    OLED_WriteCommand(0xD9); // pre-charge period
    OLED_WriteCommand(0x22);
    OLED_WriteCommand(0xDA); // com pins config
    OLED_WriteCommand(0x12);
    OLED_WriteCommand(0xDB); // vcomh
    OLED_WriteCommand(0x20);
    OLED_WriteCommand(0x8D); // charge pump
    OLED_WriteCommand(0x14);
    OLED_WriteCommand(0xAF); // display on

    OLED_Clear();
}

void OLED_ShowChar(uint8_t x, uint8_t y, char chr)
{
    uint8_t index;

    switch (chr)
    {
			case ' ': index = 0; break;

			case 'H': index = 1; break;
			case 'e': index = 2; break;
			case 'l': index = 3; break;
			case 'o': index = 4; break;

			case 'A': index = 5; break;
			case 'D': index = 6; break;
			case 'C': index = 7; break;
			case ':': index = 8; break;

			case '0': index = 9;  break;
			case '1': index = 10; break;
			case '2': index = 11; break;
			case '3': index = 12; break;
			case '4': index = 13; break;
			case '5': index = 14; break;
			case '6': index = 15; break;
			case '7': index = 16; break;
			case '8': index = 17; break;
			case '9': index = 18; break;
			
			case 'P': index = 19; break;
			case 'L': index = 20; break;
			case 'i': index = 21; break;
			case 'g': index = 22; break;
			case 'h': index = 23; break;
			case 't': index = 24; break;
			
			case 'W': index = 25; break;
			case 'c': index = 26; break;
			case 'm': index = 27; break;
			
			case ',': index = 28; break;
			
			case 'T': index = 29; break;
			case 'p': index = 30; break;
			
			case '/': index = 31; break;


			default:  index = 0; break;
    }

    OLED_SetCursor(y - 1, x - 1);
    OLED_WriteData((uint8_t *)&OLED_F6x8[index][0], 6);
}

void OLED_ShowString(uint8_t x, uint8_t y, char *str)
{
    while (*str != '\0')
    {
        OLED_ShowChar(x, y, *str);
        x += 6;   
        str++;
    }
}

void OLED_ShowChinese16(uint8_t x, uint8_t y, uint8_t index)
{
    uint8_t upper[16] = {0};
    uint8_t lower[16] = {0};
    uint8_t row, col;
    uint16_t row_data;

    for (row = 0; row < 16; row++)
    {
        row_data = (uint16_t)zh16x16[index][4 + row * 2]
                 | ((uint16_t)zh16x16[index][5 + row * 2] << 8);

        row_data = ~row_data;

        for (col = 0; col < 16; col++)
        {
            if (row_data & (1 << col))
            {
                if (col < 8)
                {
                    upper[row] |= (1 << col);
                }
                else
                {
                    lower[row] |= (1 << (col - 8));
                }
            }
        }
    }

    OLED_SetCursor(y - 1, x - 1);
    OLED_WriteData(upper, 16);

    OLED_SetCursor(y, x - 1);
    OLED_WriteData(lower, 16);
}


void OLED_ShowStringCenter(uint8_t y, char *str)
{
    uint8_t len = 0;
    uint8_t x;

    while (str[len] != '\0')
    { 
        len++;
    }

    x = (128 - len * 6) / 2 + 1;
    OLED_ShowString(x, y, str);
}

void OLED_ShowChineseCenter16(uint8_t y, uint8_t start_index, uint8_t count)
{
    uint8_t i;
    uint8_t x;

    x = (128 - count * 16) / 2 + 1;

    for (i = 0; i < count; i++)
    {
        OLED_ShowChinese16(x + i * 16, y, start_index + i);
    }
}

void OLED_ShowBMP(uint8_t x, uint8_t y, uint8_t w, uint8_t h, const uint8_t *bmp)
{
    uint8_t page, row, col;
    uint8_t pages = h / 8;
    uint8_t line[128];
    uint16_t bytes_per_row = w / 8;

    for (page = 0; page < pages; page++)
    {
        for (col = 0; col < w; col++)
        {
            line[col] = 0x00;
        }

        for (row = 0; row < 8; row++)
        {
            uint8_t src_y = page * 8 + row;

            for (col = 0; col < w; col++)
            {
                uint16_t byte_index = src_y * bytes_per_row + (col / 8);
                uint8_t byte_data = bmp[byte_index];

              
                uint8_t pixel = (byte_data >> (col % 8)) & 0x01;

                if (pixel)
                {
                    line[col] |= (1 << row);
                }
            }
        }

        OLED_SetCursor((y - 1) + page, x - 1);
        OLED_WriteData(line, w);
    }
}


void OLED_ClearArea(uint8_t x, uint8_t y, uint8_t w, uint8_t h)
{
    uint8_t page;
    uint8_t pages = h / 8;
    uint8_t zero[128];
    uint8_t i;

    for (i = 0; i < 128; i++)
    {
        zero[i] = 0x00;
    }

    for (page = 0; page < pages; page++)
    {
        OLED_SetCursor((y - 1) + page, x - 1);
        OLED_WriteData(zero, w);
    }
}

void OLED_ShowChinese16Clip(int16_t x, uint8_t y, uint8_t index)
{
    uint8_t upper[16] = {0};
    uint8_t lower[16] = {0};
    uint8_t row, col;
    uint16_t row_data;
    int16_t start, end;
    uint8_t draw_x;

    for (row = 0; row < 16; row++)
    {
        row_data = (uint16_t)zh16x16[index][4 + row * 2]
                 | ((uint16_t)zh16x16[index][5 + row * 2] << 8);

        row_data = ~row_data;

        for (col = 0; col < 16; col++)
        {
            if (row_data & (1 << col))
            {
                if (col < 8)
                {
                    upper[row] |= (1 << col);
                }
                else
                {
                    lower[row] |= (1 << (col - 8));
                }
            }
        }
    }

    if (x <= -16 || x >= 128)
    {
        return;
    }

    start = 0;
    end = 16;

    if (x < 0)
    {
        start = -x;
    }

    if (x + 16 > 128)
    {
        end = 128 - x;
    }

    if (start >= end)
    {
        return;
    }

    draw_x = (x < 0) ? 0 : (uint8_t)x;

    OLED_SetCursor(y - 1, draw_x);
    OLED_WriteData(&upper[start], end - start);

    OLED_SetCursor(y, draw_x);
    OLED_WriteData(&lower[start], end - start);
}

